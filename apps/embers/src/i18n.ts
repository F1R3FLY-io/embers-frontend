import type { ParseKeys } from "i18next";

import i18n from "i18next";
import { initReactI18next } from "react-i18next";

type Resource = {
  translation: Record<string, string>;
};

type Resources = Record<string, Resource>;

const modules: Record<string, { default: Record<string, string> }> =
  import.meta.glob("./i18n/*.json", { eager: true });

const resources: Resources = Object.fromEntries(
  Object.entries(modules).map(([path, value]) => {
    const lang = path.match(/\/([a-z]+)\.json$/i)?.[1];
    if (!lang) {
      return [];
    }
    return [lang, { translation: value.default }];
  }),
) as Resources;

void i18n.use(initReactI18next).init({
  fallbackLng: "en",
  interpolation: { escapeValue: false },
  lng: "en",
  react: { useSuspense: false },
  resources,
  // Treat an empty translation as missing, so it falls back to English.
  //
  // i18next returns "" as a perfectly good translation by default. The German
  // and French catalogues were generated by `sync-i18n`, which fills every
  // untranslated key with "" -- 148 of 168 keys in each -- so selecting either
  // language rendered a mostly BLANK interface: buttons with no label,
  // headings with no text. A key that is absent entirely already fell back to
  // English correctly, which is why the five newest keys looked fine while
  // everything around them vanished.
  //
  // English text in a German interface is a visible gap someone can fix. A
  // blank button is not: it looks like a rendering fault, and it gives the
  // user nothing to report.
  returnEmptyString: false,
});

export type TranslationKey = ParseKeys;

export default i18n;
